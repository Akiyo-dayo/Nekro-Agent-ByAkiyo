async def upgrade(db: BaseDBAsyncClient) -> str:
    return """-- 先清存量重复行：同一联合键只留最早一行（内测阶段口径，已拍板不保留副本分叉）
        DELETE FROM "user" a USING "user" b
        WHERE a."adapter_key" <> '' AND a."adapter_key" = b."adapter_key"
          AND a."platform_userid" = b."platform_userid" AND a."id" > b."id";
        -- 联合键部分唯一索引：('','') 空键是控制台账号（admin/租户成员）的合法共享形态，
        -- 约束只罩聊天平台用户（adapter_key 恒非空）
        CREATE UNIQUE INDEX IF NOT EXISTS "uid_user_adapter_platform"
            ON "user"("adapter_key", "platform_userid") WHERE "adapter_key" <> '';"""


async def downgrade(db: BaseDBAsyncClient) -> str:
    return """
        DROP INDEX IF EXISTS "uid_user_adapter_platform";"""


