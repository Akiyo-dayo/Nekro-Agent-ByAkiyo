from tortoise import BaseDBAsyncClient

RUN_IN_TRANSACTION = True


async def upgrade(db: BaseDBAsyncClient) -> str:
    # 书级预算从「字」换成「token」：改列名保留数据，值按 1 字 = 0.8 token 换算（0 仍为 0，
    # 上限 65536 与全局 token 上限一致）。aerich 生成的是删列再加列，会把每本书设过的预算清零，改成了改名。
    # 新的 JSON 列带默认值：已有的明细行不能因为加列失败。
    return """
        ALTER TABLE "mem_prompt_round" ADD "worldbook_budget" JSONB NOT NULL DEFAULT '{}'::jsonb;
        COMMENT ON COLUMN "mem_prompt_round"."worldbook_items" IS '世界书条目引用、字数与 token 数';
        ALTER TABLE "model_group" ADD "context_length" INT NOT NULL DEFAULT 0;
        ALTER TABLE "model_group" ADD "token_count_factor" DOUBLE PRECISION NOT NULL DEFAULT 0;
        ALTER TABLE "wb_book" RENAME COLUMN "budget_chars" TO "budget_tokens";
        UPDATE "wb_book" SET "budget_tokens" = LEAST(65536, ROUND("budget_tokens" * 0.8)) WHERE "budget_tokens" > 0;
        COMMENT ON COLUMN "mem_prompt_round"."worldbook_budget" IS '这一轮的世界书预算与算法：模型组、上下文长度、百分比、上限、分词系数、最终预算（token）';
COMMENT ON COLUMN "model_group"."context_length" IS '上下文长度（token）；0 表示未填，世界书预算按 32768 估';
COMMENT ON COLUMN "model_group"."token_count_factor" IS '分词系数（相对 o200k_base）；0 表示按模型名自动取';
COMMENT ON COLUMN "wb_book"."budget_tokens" IS '本书每轮最多注入多少 token；0 表示不单独限制';"""


async def downgrade(db: BaseDBAsyncClient) -> str:
    # 回到字数口径：值按 ÷ 0.8 换回（0 仍为 0，上限 100000 与旧的书级上限一致），再改回列名
    return """
        UPDATE "wb_book" SET "budget_tokens" = LEAST(100000, ROUND("budget_tokens" / 0.8)) WHERE "budget_tokens" > 0;
        ALTER TABLE "wb_book" RENAME COLUMN "budget_tokens" TO "budget_chars";
        ALTER TABLE "model_group" DROP COLUMN "context_length";
        ALTER TABLE "model_group" DROP COLUMN "token_count_factor";
        ALTER TABLE "mem_prompt_round" DROP COLUMN "worldbook_budget";
        COMMENT ON COLUMN "mem_prompt_round"."worldbook_items" IS '世界书条目引用与字数';
        COMMENT ON COLUMN "wb_book"."budget_chars" IS '本书每轮最多注入多少字；0 表示不单独限制';"""


