"""给 Agent 调用的运维工具

## 它解决什么问题

平台方在 QQ 里跟 Bot 说一句「inst3 是不是掉线了」，希望 Bot 自己去查、直接答，
而不是让人再打开总后台翻页面。这些工具因此**直接挂在 Agent 的沙盒方法清单里**，
由模型在回合中按需调用，不设前缀、不设「运维模式」，也不需要额外的一条命令通道。

## 为什么不是插件

插件的启用状态与配置对**租户管理员**可见可改（插件启停页、插件配置页），
把运维能力做成插件等于给租户一条自助开关：他可以在自己名下的实例上打开它，
再配合一个自己填的发送者 ID 去碰运气。运维工具的鉴权不能建立在租户能改的东西上。
另外插件可以热重载、卸载、从市场覆盖安装，而这条通道的判据（谁在什么地点触发了这一轮）
不应该有这种生命周期。

因此它是一个核心服务：方法提供者直接接进 `services/plugin/collector.py` 的清单与
`routers/rpc.py` 的分派，提示词由 `run_agent` 直接拼接，**不经过** `loaded_plugins`。

## 判据只看宿主侧事实

一轮能不能拿到工具，取决于四样宿主自己算得出来的东西：

1. 这一轮由谁触发（`triggers.py`，在入站事件自己的任务里记下，不读消息正文、不读模型的话）；
2. 触发者的来源是否可信（`services/user/super_users.py` 的同一套判定）；
3. 频道是不是允许的地点（`policy.py` 的 `RoundFacts`）；
4. 频道所在实例归不归平台方。

模型说的任何关于身份的话都不进入判定：工具的签名里没有「操作者」这类参数，
判定函数也没有接收模型输入的入口。

## 开关

总开关 `OPS_AGENT_TOOLS_ENABLED` 默认关。关着时这一整包不产生任何可观察差异：
不查库、不建授权、方法清单与提示词与改造前逐字一致（见 `provider.methods_for` 与
`provider.render_prompt_section` 的第一行判定）。
"""
